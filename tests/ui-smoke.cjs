    await submitAdd();
    assert.deepEqual(await evaluate('window.testApi.calls().filter(c=>c.method==="import").at(-1).keys'),['codex/pasted']);
    assert.deepEqual(await evaluate('window.testApi.calls().filter(c=>c.method==="import").at(-1).names'),{'codex/pasted':'pasted-account'});
    await evaluate('window.testApi.setImportMode("canceled")');
    await openAdd('backup'); await click('#btnChooseBackup');
    assert.equal(await evaluate('document.querySelector("#saveModalOverlay").open'),true);
    assert.equal(await evaluate('document.querySelector("#addAccountError").textContent'),'');
    await click('[data-action=closeSaveModal]');
    await click('[data-action=openSaveModal]');
    assert.equal(await evaluate('document.querySelector("#saveModalOverlay").open'),true);
